import { describe, expect, it } from "vitest";
import { parseFlexibleDate } from "@/lib/dates";

const NOW = new Date("2026-11-05T10:00:00Z");

describe("parseFlexibleDate", () => {
  it.each([
    ["12.04.1985", "1985-04-12"],
    ["12.4.1985", "1985-04-12"],
    ["1.4.85", "1985-04-01"],
    ["12.04.05", "2005-04-12"],
    ["12. 04. 1985", "1985-04-12"],
    ["12/04/1985", "1985-04-12"],
    ["12-04-1985", "1985-04-12"],
    ["1985-04-12", "1985-04-12"],
    ["1985-4-2", "1985-04-02"],
    ["12. April 1985", "1985-04-12"],
    ["3. März 1990", "1990-03-03"],
    ["3 Maerz 1990", "1990-03-03"],
    ["5. Sept. 1971", "1971-09-05"],
    ["01. Dez 2026", "2026-12-01"],
    ["15 March 1980", "1980-03-15"],
    ["am 01.12.2026", "2026-12-01"],
    ["  29.02.2024 ", "2024-02-29"],
  ])("parses %s", (raw, expected) => {
    expect(parseFlexibleDate(raw, NOW)).toBe(expected);
  });

  it.each([
    "",
    "gestern",
    "31.02.2025",
    "29.02.2025",
    "04.13.1985",
    "00.01.1985",
    "12.04.198",
    "12. Foo 1985",
    "12.04.1985 um 10 Uhr",
  ])("rejects %s", (raw) => {
    expect(parseFlexibleDate(raw, NOW)).toBeNull();
  });
});
